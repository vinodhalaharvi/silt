// Package emit writes the two configuration files Buildroot and kbuild
// consume. Silt compiles nothing; these files are its only output artifact.
package emit

import (
	"fmt"
	"regexp"
	"sort"
	"strings"

	"github.com/vinodhalaharvi/silt/compose"
	"github.com/vinodhalaharvi/silt/kconfig"
	"github.com/vinodhalaharvi/silt/lang"
)

// Defconfig renders a Buildroot defconfig or a Linux .config fragment.
//
// At Rung 2 only stated constraints are emitted; the file is partial and
// olddefconfig completes it. Rung 7 replaces that with a solved total
// assignment, and this function's output does not otherwise change.
// Defconfig renders one tree's configuration.
//
// linuxFragment, when non-empty, is the absolute path of the emitted
// linux.config. Buildroot is told to layer it over the kernel's own defconfig
// via BR2_LINUX_KERNEL_CONFIG_FRAGMENT_FILES. Without this the Linux half of
// every fragment is produced and then silently ignored, which is exactly the
// two-halves-disagreeing problem Silt exists to remove — committed by Silt
// itself.
func DefconfigWithKernel(r *compose.Result, sc lang.Scope, linuxFragment string) string {
	out := Defconfig(r, sc)
	if sc != lang.Buildroot {
		return out
	}
	var extra strings.Builder
	if v := r.Image.Version; v != "" {
		fmt.Fprintf(&extra, "BR2_LINUX_KERNEL_CUSTOM_VERSION=y\n")
		fmt.Fprintf(&extra, "BR2_LINUX_KERNEL_CUSTOM_VERSION_VALUE=%q\n", v)
	}
	// Only when there is a Linux half. Pointing Buildroot at an empty fragment
	// builds the same kernel, but it adds a line the source config never had,
	// so no imported defconfig could round-trip through emit.
	if linuxFragment != "" && hasHard(r.Constraints[lang.Linux]) {
		fmt.Fprintf(&extra, "BR2_LINUX_KERNEL_CONFIG_FRAGMENT_FILES=%q\n", linuxFragment)
	}
	return out + extra.String()
}

func Defconfig(r *compose.Result, sc lang.Scope) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by silt from %s. Do not edit.\n", r.Image.Name)
	fmt.Fprintf(&b, "# Fragments: %s\n", strings.Join(fragmentNames(r.Fragments), " "))

	tree := r.Tree()
	untyped := 0
	lines := map[string]string{}
	emitLine := func(c lang.Constraint) {
		if c.IsValue && tree == nil && numeric.MatchString(c.Value) {
			untyped++
		}
		if l := typedLine(c, tree); l != "" {
			lines[c.Symbol] = l
		}
	}
	for _, c := range r.Constraints[sc] {
		if c.Soft {
			continue // soft constraints need MaxSAT; nothing to emit before Rung 7
		}
		emitLine(c)
	}
	// Opaque values are emitted verbatim: carried, not reasoned about.
	for _, c := range r.Opaque {
		if scopeFor(c.Symbol) == sc {
			emitLine(c)
		}
	}
	if untyped > 0 {
		// Invariant 9: a loss must appear in the output.
		fmt.Fprintf(&b, "# WARNING: %d numeric value(s) written quoted without a tree to type them;\n"+
			"# kbuild ignores a quoted int or hex. Emit with --buildroot.\n", untyped)
	}
	if sc == lang.Linux && r.Image.Version != "" {
		// custom-version is a Buildroot-side instruction about the kernel, so
		// it is a comment here and a real symbol on the Buildroot side.
		fmt.Fprintf(&b, "# kernel version requested: %s\n", r.Image.Version)
	}

	keys := make([]string, 0, len(lines))
	for k := range lines {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		b.WriteString(lines[k])
		b.WriteByte('\n')
	}
	return b.String()
}

var numeric = regexp.MustCompile(`^(-?[0-9]+|0[xX][0-9a-fA-F]+)$`)

// typedLine writes int and hex symbols bare. Every value in a fragment is a
// string, and writing BR2_TARGET_ROOTFS_UBI_SUBSIZE="2048" looks right and is
// silently discarded by kbuild, which wants 2048. Found by importing
// at91sam9x5ek_defconfig and diffing the round trip.
func typedLine(c lang.Constraint, tree *kconfig.Tree) string {
	if c.IsValue && tree != nil {
		if s := tree.Symbols[c.Symbol]; s != nil && (s.Type == kconfig.Int || s.Type == kconfig.Hex) {
			return fmt.Sprintf("%s=%s", c.Symbol, c.Value)
		}
	}
	return line(c)
}

func line(c lang.Constraint) string {
	switch {
	case c.IsValue:
		return fmt.Sprintf("%s=%q", c.Symbol, c.Value)
	case c.AtLeast:
		// The weakest thing satisfying "m or stronger" is m. Choosing between
		// m and y is the solver's job, so before Rung 7 take the weaker.
		return fmt.Sprintf("%s=%s", c.Symbol, c.Want)
	case c.Want == lang.N:
		return fmt.Sprintf("# %s is not set", c.Symbol)
	default:
		return fmt.Sprintf("%s=%s", c.Symbol, c.Want)
	}
}

func hasHard(cs []lang.Constraint) bool {
	for _, c := range cs {
		if !c.Soft {
			return true
		}
	}
	return false
}

func scopeFor(sym string) lang.Scope {
	if strings.HasPrefix(sym, "CONFIG_") {
		return lang.Linux
	}
	return lang.Buildroot
}

func fragmentNames(frs []*lang.Fragment) []string {
	out := make([]string, len(frs))
	for i, f := range frs {
		out[i] = f.ID.String()
	}
	return out
}
